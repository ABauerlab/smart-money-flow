// Pure health / report-selection logic for crypto-analysis, free of Deno and
// Supabase imports so it can be unit tested (see src/test/health.test.ts).

// 9h = longest normal gap between the 4 daily reports (21:00 -> 05:00) plus slack.
export const STALE_AFTER_MINUTES = 9 * 60;
// A freshly ingested round generates its AI report in the background (several
// seconds, up to a couple of minutes). Do not call a missing analysis a problem
// before this grace period has passed.
export const ANALYSIS_GRACE_MINUTES = 15;
// Do not regenerate a window's report again within this many minutes of the last
// attempt, so repeated alerts/repairs cannot stack AI calls.
export const REPAIR_COOLDOWN_MINUTES = 5;

export type HealthProblemCode =
  | 'db_unreachable'
  | 'no_round'
  | 'stale'
  | 'aggregate_mismatch'
  | 'report_without_analysis';

export interface HealthProblem { code: HealthProblemCode; detail: string }

export interface HealthInput {
  dbError?: string | null;
  checks: Array<{ window: string; aggregateTotal: number; rowsTotal: number }>;
  minutesSinceLastRound: number | null;
  // Daily window (current business day): total repetitions ingested and how many
  // stored reports for it actually carry an AI analysis.
  dailyTotal: number;
  dailyReportsWithAnalysis: number;
}

export function evaluateHealth(input: HealthInput): HealthProblem[] {
  const problems: HealthProblem[] = [];
  if (input.dbError) {
    problems.push({ code: 'db_unreachable', detail: input.dbError });
    return problems;
  }
  for (const c of input.checks) {
    if (c.aggregateTotal !== c.rowsTotal) {
      problems.push({
        code: 'aggregate_mismatch',
        detail: `${c.window}: agregado=${c.aggregateTotal} linhas=${c.rowsTotal}`,
      });
    }
  }
  if (input.minutesSinceLastRound === null) {
    problems.push({ code: 'no_round', detail: 'Nenhuma rodada registrada para este código.' });
  } else if (input.minutesSinceLastRound > STALE_AFTER_MINUTES) {
    problems.push({
      code: 'stale',
      detail: `Última rodada há ${input.minutesSinceLastRound} min (limite ${STALE_AFTER_MINUTES}). O envio da VPS/Make parou.`,
    });
  }
  const pastGrace = input.minutesSinceLastRound !== null && input.minutesSinceLastRound > ANALYSIS_GRACE_MINUTES;
  if (input.dailyTotal > 0 && input.dailyReportsWithAnalysis === 0 && pastGrace) {
    problems.push({
      code: 'report_without_analysis',
      detail: 'O relatório diário de hoje existe sem análise de IA (falha da IA durante a geração).',
    });
  }
  return problems;
}

// Decide whether a window's report must be (re)generated by the repair action.
export function needsReportRepair(
  s: { total: number; withAnalysis: number; lastCreatedAt: string | null },
  now = Date.now(),
): boolean {
  if (s.total <= 0 || s.withAnalysis > 0) return false;
  if (!s.lastCreatedAt) return true;
  const ageMin = (now - new Date(s.lastCreatedAt).getTime()) / 60000;
  return !(ageMin < REPAIR_COOLDOWN_MINUTES);
}

// One report id per (type, start, end) window, newest first, capped at `limit`.
// Within a window the newest report WITH an AI analysis wins; only when none has one
// does the newest analysis-less report show. Without this, a single failed AI call
// (empty report inserted last) hid the good screening of the same window.
export function pickReportIds(
  index: Array<{ id: string; period_type: string; period_start: string; period_end: string }>,
  goodIds: Set<string>,
  limit = 40,
): string[] {
  const order: string[] = [];
  const chosen = new Map<string, string>();
  for (const r of index) {
    const key = `${r.period_type}|${r.period_start}|${r.period_end}`;
    const cur = chosen.get(key);
    if (cur === undefined) { chosen.set(key, r.id); order.push(key); }
    else if (!goodIds.has(cur) && goodIds.has(r.id)) chosen.set(key, r.id);
  }
  return order.slice(0, limit).map(k => chosen.get(k)!);
}
